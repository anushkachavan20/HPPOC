"""
K6 Result Parser - Parse and validate k6 test execution results.

Supports:
1. Custom POC JSON format:
   {
       "k6_meta": {...},
       "results": [...]
   }

2. Native k6 JSON output:
   JSON Lines generated by:
       k6 run --out json=results.json
"""

import json
from typing import Any, Dict, List, Optional
from pathlib import Path
from datetime import datetime

from pydantic import BaseModel, validator

from logger import get_logger


logger = get_logger('ingestion.k6_parser')


# ============================================================
# Models
# ============================================================

class K6TestResult(BaseModel):
    """Model for a single k6 test result."""

    service: str
    test_name: str
    method: str
    endpoint: str
    status: str
    http_status: int
    duration_ms: float
    error: Optional[str] = None
    response_body: Optional[str] = None
    timestamp: Optional[str] = None

    @validator('status')
    def validate_status(cls, v):
        value = v.upper()

        if value not in ['PASS', 'FAIL']:
            raise ValueError(
                f"Status must be PASS or FAIL, got {v}"
            )

        return value

    class Config:
        allow_population_by_field_name = True


class K6Metadata(BaseModel):
    """Model for k6 execution metadata."""

    execution_id: str
    scenario: str
    duration: Optional[str] = None
    vus: Optional[int] = None
    timestamp: Optional[str] = None


class K6ExecutionResult(BaseModel):
    """Complete k6 execution result."""

    k6_meta: K6Metadata
    results: List[K6TestResult]


# ============================================================
# Parser
# ============================================================

class K6ResultParser:
    """Parser for custom and native k6 JSON output."""

    # Map the test names used in the k6 group() calls
    # to the endpoint expected by the analysis pipeline.
    ENDPOINT_MAP = {

        # Current public API test files
        'GetPosts': '/posts',
        'GetPost': '/posts/1',
        'NotFound': '/posts/999999999',
        'GetUsers': '/api/users?page=2',
        'GetUser': '/api/users/2',
        'Unauthorized': '/status/401',
        'Get': '/get',
        'UUID': '/uuid',
        'ServerError': '/status/500',

        # Customer
        'CreateCustomer': '/customers',
        'GetCustomer': '/customers/{id}',
        'UpdateCustomer': '/customers/{id}',
        'DeleteCustomer': '/customers',

        # Order
        'CreateOrder': '/orders',
        'GetOrder': '/orders/{id}',
        'UpdateOrder': '/orders/{id}',
        'CancelOrder': '/orders/{id}',

        # Payment
        'CreatePayment': '/payments',
        'GetPayment': '/payments/{id}',
        'UpdatePayment': '/payments/{id}',
        'RefundPayment': '/payments/{id}/refund',
    }

    def __init__(self):
        self.logger = logger

    # ========================================================
    # Main parser
    # ========================================================

    def parse_k6_json(
        self,
        json_file: str,
        execution_id: Optional[str] = None
    ) -> Optional[K6ExecutionResult]:
        """
        Parse either custom POC JSON or native k6 JSON.

        Args:
            json_file:
                Path to the k6 result file.

            execution_id:
                Optional execution ID supplied by GitHub Actions.

        Returns:
            K6ExecutionResult or None if parsing fails.
        """

        try:

            json_path = Path(json_file)

            if not json_path.exists():

                self.logger.error(
                    f"K6 result file not found: {json_file}"
                )

                return None

            # ------------------------------------------------
            # Read file
            # ------------------------------------------------

            with open(
                json_path,
                'r',
                encoding='utf-8'
            ) as f:

                content = f.read().strip()

            if not content:

                self.logger.error(
                    f"K6 result file is empty: {json_file}"
                )

                return None

            # ------------------------------------------------
            # First try normal JSON
            # ------------------------------------------------

            try:

                data = json.loads(content)

                # Existing POC format:
                #
                # {
                #     "k6_meta": {},
                #     "results": []
                # }

                if (
                    isinstance(data, dict)
                    and 'k6_meta' in data
                    and 'results' in data
                ):

                    if execution_id:

                        data['k6_meta']['execution_id'] = (
                            execution_id
                        )

                    result = K6ExecutionResult(
                        **data
                    )

                    self.logger.info(
                        f"Parsed custom k6 results: "
                        f"{len(result.results)} test results "
                        f"from execution "
                        f"{result.k6_meta.execution_id}"
                    )

                    return result

            except json.JSONDecodeError:

                # Native k6 output is JSON Lines.
                #
                # Therefore the entire file isn't valid
                # JSON and we continue to the native parser.

                pass

            # ------------------------------------------------
            # Parse native k6 JSON Lines
            # ------------------------------------------------

            return self._parse_native_k6_json(
                content,
                execution_id
            )

        except Exception as e:

            self.logger.error(
                f"Failed to parse k6 results: {e}",
                exc_info=True
            )

            return None

    # ========================================================
    # Native k6 parser
    # ========================================================

    def _parse_native_k6_json(
        self,
        content: str,
        execution_id: Optional[str]
    ) -> Optional[K6ExecutionResult]:
        """
        Parse native k6 JSON Lines output.

        The parser uses http_req_duration points because
        each HTTP request produces a duration metric containing
        useful tags such as:

        - group
        - method
        - status
        - url
        - name
        """

        points = []

        # ----------------------------------------------------
        # Read every JSON line
        # ----------------------------------------------------

        for line in content.splitlines():

            line = line.strip()

            if not line:
                continue

            try:

                record = json.loads(line)

            except json.JSONDecodeError:

                continue

            # ------------------------------------------------
            # Only Point records
            # ------------------------------------------------

            if record.get('type') != 'Point':
                continue

            # ------------------------------------------------
            # Only HTTP duration records
            # ------------------------------------------------

            if record.get('metric') != 'http_req_duration':
                continue

            data = record.get(
                'data',
                {}
            )

            tags = data.get(
                'tags'
            ) or {}

            points.append(
                {
                    'time': data.get('time'),
                    'duration': data.get('value'),
                    'tags': tags,
                }
            )

        # ----------------------------------------------------
        # Validate points
        # ----------------------------------------------------

        if not points:

            self.logger.error(
                "No http_req_duration points found "
                "in native k6 output"
            )

            return None

        self.logger.debug(
            f"Found {len(points)} http_req_duration points"
        )

        # ----------------------------------------------------
        # Convert points to our standard model
        # ----------------------------------------------------

        results = []

        for point in points:

            tags = point['tags']

            # Example:
            #
            # ::Customer Service - CreateCustomer::
            #
            group = tags.get(
                'group',
                ''
            )

            method = tags.get(
                'method',
                'GET'
            )

            status = tags.get(
                'status',
                '0'
            )

            # ------------------------------------------------
            # Identify test
            # ------------------------------------------------

            test_name = self._extract_test_name(
                group
            )

            if not test_name:

                self.logger.warning(
                    f"Could not determine test name "
                    f"from group: {group}"
                )

                continue

            # ------------------------------------------------
            # Identify service
            # ------------------------------------------------

            service = self._extract_service(
                group
            )

            # ------------------------------------------------
            # HTTP status
            # ------------------------------------------------

            try:

                http_status = int(status)

            except (
                TypeError,
                ValueError
            ):

                http_status = 0

            # ------------------------------------------------
            # Duration
            # ------------------------------------------------

            try:

                duration_ms = float(
                    point.get('duration') or 0
                )

            except (
                TypeError,
                ValueError
            ):

                duration_ms = 0.0

            # ------------------------------------------------
            # Determine PASS / FAIL
            # ------------------------------------------------

            passed = (
                http_status >= 200
                and http_status < 400
            )

            if passed:

                result_status = 'PASS'
                error = None

            else:

                result_status = 'FAIL'

                error = (
                    f"HTTP status {http_status}"
                )

            # ------------------------------------------------
            # Endpoint
            # ------------------------------------------------

            endpoint = next(
                (
                    mapped_endpoint
                    for mapped_test, mapped_endpoint
                    in self.ENDPOINT_MAP.items()
                    if mapped_test.lower() == test_name.lower()
                ),
                '/',
            )

            # ------------------------------------------------
            # Build model
            # ------------------------------------------------

            results.append(
                K6TestResult(
                    service=service,
                    test_name=test_name,
                    method=method,
                    endpoint=endpoint,
                    status=result_status,
                    http_status=http_status,
                    duration_ms=duration_ms,
                    error=error,
                    response_body='',
                    timestamp=point.get('time')
                )
            )

        # ----------------------------------------------------
        # Validate results
        # ----------------------------------------------------

        if not results:

            self.logger.error(
                "Native k6 output was parsed, "
                "but no API test results could be constructed"
            )

            return None

        # ----------------------------------------------------
        # Generate execution ID
        # ----------------------------------------------------

        if not execution_id:

            execution_id = (
                f"k6_"
                f"{datetime.utcnow().strftime('%Y%m%d%H%M%S')}"
            )

        # ----------------------------------------------------
        # Build metadata
        # ----------------------------------------------------

        metadata = K6Metadata(
            execution_id=execution_id,
            scenario='api_tests',
            duration=None,
            vus=1,
            timestamp=(
                datetime.utcnow().isoformat()
                + 'Z'
            )
        )

        # ----------------------------------------------------
        # Build final result
        # ----------------------------------------------------

        result = K6ExecutionResult(
            k6_meta=metadata,
            results=results
        )

        self.logger.info(
            f"Parsed native k6 results: "
            f"{len(results)} test results "
            f"from execution {execution_id}"
        )

        return result

    # ========================================================
    # Extract test name
    # ========================================================

    def _extract_test_name(
        self,
        group: str
    ) -> Optional[str]:
        """
        Convert:

            ::Customer Service - CreateCustomer::

        into:

            CreateCustomer
        """

        if not group:

            return None

        clean_group = (
            group
            .replace('::', '')
            .strip()
        )

        if ' - ' in clean_group:

            return (
                clean_group
                .split(' - ', 1)[1]
                .strip()
            )

        return clean_group

    # ========================================================
    # Extract service
    # ========================================================

    def _extract_service(
        self,
        group: str
    ) -> str:
        """
        Convert:

            ::Customer Service - CreateCustomer::

        into:

            customer
        """

        if not group:

            return 'unknown'

        clean_group = (
            group
            .replace('::', '')
            .strip()
        )

        if ' Service - ' in clean_group:

            service = (
                clean_group
                .split(
                    ' Service - ',
                    1
                )[0]
            )

            return service.lower()

        return 'unknown'

    # ========================================================
    # Parse dictionary
    # ========================================================

    def parse_k6_dict(
        self,
        data: Dict[str, Any]
    ) -> Optional[K6ExecutionResult]:
        """
        Parse k6 result from a dictionary.
        """

        try:

            result = K6ExecutionResult(
                **data
            )

            self.logger.info(
                f"Parsed k6 results from dict: "
                f"{len(result.results)} test results "
                f"from execution "
                f"{result.k6_meta.execution_id}"
            )

            return result

        except Exception as e:

            self.logger.error(
                f"Failed to parse k6 results "
                f"from dict: {e}"
            )

            return None

    # ========================================================
    # Normalize one result
    # ========================================================

    def normalize_test_result(
        self,
        test: K6TestResult,
        execution_id: str,
        timestamp: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Normalize a single test result for Datadog.
        """

        ts = (
            timestamp
            or test.timestamp
            or datetime.utcnow().isoformat() + 'Z'
        )

        return {
            'execution_id': execution_id,

            'service': test.service.lower(),

            'test': test.test_name.lower(),

            'method': test.method.upper(),

            'endpoint': test.endpoint,

            'status': test.status.upper(),

            'http_status': test.http_status,

            'duration_ms': test.duration_ms,

            'error_message': (
                test.error or ''
            ),

            'response_body': (
                test.response_body or ''
            ),

            'timestamp': ts,
        }

    # ========================================================
    # Normalize all results
    # ========================================================

    def normalize_results(
        self,
        execution: K6ExecutionResult,
        timestamp: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Normalize all k6 results for Datadog ingestion.
        """

        normalized = []

        for test in execution.results:

            normalized.append(
                self.normalize_test_result(
                    test,
                    execution.k6_meta.execution_id,
                    timestamp
                )
            )

        return normalized